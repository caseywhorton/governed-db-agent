"""
export_postgres_seed.py — Write postgres_seed.sql: the project's schema and sample data as SQL for Postgres.

    python export_postgres_seed.py                  # writes postgres_seed.sql
    python export_postgres_seed.py --out other.sql

It reuses the generator in setup_db.py (same seed), so Postgres gets exactly the rows SQLite has:
the three original customers plus the generated ones. Nothing in your SQLite database is read or changed.

Load the result with:
    docker compose exec -T db psql -U governed -d governed -v ON_ERROR_STOP=1 -P pager=off < postgres_seed.sql

The script is safe to run again: tables use IF NOT EXISTS and every insert uses ON CONFLICT DO NOTHING.

Choices made for Postgres:
  - balance and amount are numeric(12,2), the right type for money, and what lets ROUND(x, 2) work
    (Postgres has no ROUND(double precision, integer)).
  - dates stay as text, so queries like substr(date, 1, 7) keep working. Moving to a real date
    column is a good later step, but it means rewriting those queries.
"""

import argparse
import random
from pathlib import Path

import setup_db

SCHEMA_SQL = """
CREATE TABLE IF NOT EXISTS customers (
    id integer PRIMARY KEY,
    name text NOT NULL,
    segment text NOT NULL,
    created_at text NOT NULL
);

CREATE TABLE IF NOT EXISTS accounts (
    id integer PRIMARY KEY,
    customer_id integer NOT NULL REFERENCES customers(id),
    account_type text NOT NULL,
    balance numeric(12,2) NOT NULL
);

CREATE TABLE IF NOT EXISTS transactions (
    id integer PRIMARY KEY,
    account_id integer NOT NULL REFERENCES accounts(id),
    amount numeric(12,2) NOT NULL,
    date text NOT NULL,
    flagged integer NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS customer_profiles (
    customer_id integer PRIMARY KEY REFERENCES customers(id),
    full_name text NOT NULL,
    email text NOT NULL,
    phone text NOT NULL,
    ssn text NOT NULL,
    date_of_birth text NOT NULL,
    street_address text NOT NULL,
    city text NOT NULL,
    state text NOT NULL,
    credit_band text NOT NULL,
    signup_channel text NOT NULL
);
"""

CHUNK = 500  # rows per INSERT statement


def literal(value):
    """One value as a SQL literal."""
    if isinstance(value, str):
        return "'" + value.replace("'", "''") + "'"
    if isinstance(value, bool):
        return "1" if value else "0"
    if isinstance(value, (int, float)):
        return repr(value)
    raise TypeError(f"unsupported value: {value!r}")


def inserts(table, columns, rows):
    """INSERT statements for one table, in chunks, safe to run twice."""
    out = []
    names = ", ".join(columns)
    for start in range(0, len(rows), CHUNK):
        chunk = rows[start:start + CHUNK]
        values = ",\n  ".join("(" + ", ".join(literal(v) for v in row) + ")" for row in chunk)
        out.append(f"INSERT INTO {table} ({names}) VALUES\n  {values}\nON CONFLICT DO NOTHING;")
    return out


def build_sql():
    extra_customers, extra_accounts, extra_profiles, extra_txns = setup_db.generate(
        random.Random(setup_db.SEED)
    )
    customers = setup_db.BASE_CUSTOMERS + extra_customers
    accounts = setup_db.BASE_ACCOUNTS + extra_accounts
    profiles = setup_db.BASE_PROFILES + extra_profiles
    transactions = setup_db.BASE_TRANSACTIONS + extra_txns

    parts = [
        "-- Generated by export_postgres_seed.py from the same seeded data as setup_db.py.",
        "-- Safe to run again. All values are fake.",
        "BEGIN;",
        SCHEMA_SQL.strip(),
        *inserts("customers", ["id", "name", "segment", "created_at"], customers),
        *inserts("accounts", ["id", "customer_id", "account_type", "balance"], accounts),
        *inserts(
            "customer_profiles",
            ["customer_id", "full_name", "email", "phone", "ssn", "date_of_birth",
             "street_address", "city", "state", "credit_band", "signup_channel"],
            profiles,
        ),
        *inserts("transactions", ["id", "account_id", "amount", "date", "flagged"], transactions),
        "COMMIT;",
        "",
        "-- Row counts, so you can check the load.",
        "SELECT 'customers' AS table_name, count(*) AS row_count FROM customers\n"
        "UNION ALL SELECT 'accounts', count(*) FROM accounts\n"
        "UNION ALL SELECT 'transactions', count(*) FROM transactions\n"
        "UNION ALL SELECT 'customer_profiles', count(*) FROM customer_profiles;",
    ]
    counts = {"customers": len(customers), "accounts": len(accounts),
              "transactions": len(transactions), "customer_profiles": len(profiles)}
    return "\n\n".join(parts) + "\n", counts


def main():
    parser = argparse.ArgumentParser(description="Export the sample data as Postgres SQL.")
    parser.add_argument("--out", default="postgres_seed.sql")
    args = parser.parse_args()

    sql, counts = build_sql()
    Path(args.out).write_text(sql)
    print(f"Wrote {args.out} ({len(sql):,} characters). Expected row counts after loading:")
    for table, n in counts.items():
        print(f"  {table}: {n}")


if __name__ == "__main__":
    main()